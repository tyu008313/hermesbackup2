#!/bin/bash
set -euo pipefail

CONFIG_DIR="/data/.hermes/enterprise/config"
ENV_FILE="${CONFIG_DIR}/env.conf"
REPO_URL="https://github.com/tyu008313/hermesbackup2"

if [ -f "$ENV_FILE" ]; then
    export GITHUB_TOKEN=$(grep '^GITHUB_TOKEN=' "$ENV_FILE" | cut -d'=' -f2)
fi

GIT_TOKEN="${GITHUB_TOKEN:-}"

if [ -z "$GIT_TOKEN" ]; then
    echo "GITHUB_TOKEN required."
    exit 1
fi

REPO_PATH=$(echo $REPO_URL | sed 's|https://github.com/||')
REPO_OWNER=$(echo $REPO_PATH | cut -d'/' -f1)
REPO_NAME=$(echo $REPO_PATH | cut -d'/' -f2 | sed 's|.git$||')

TIMESTAMP=$(date +"%Y-%m-%d_%H-%M-%S")
STAGING_DIR="/tmp/hermes_final_sync_${TIMESTAMP}"
mkdir -p "${STAGING_DIR}/core" "${STAGING_DIR}/intelligence" "${STAGING_DIR}/skills" "${STAGING_DIR}/interactions" "${STAGING_DIR}/enterprise"

echo "📦 Syncing structured Hermes core & environment to GitHub..."

cp /data/.hermes/config.yaml "${STAGING_DIR}/core/" 2>/dev/null || true
cp /data/.hermes/SOUL.md "${STAGING_DIR}/intelligence/" 2>/dev/null || true
cp -r /data/.hermes/memories/* "${STAGING_DIR}/intelligence/" 2>/dev/null || true
cp -r /data/.hermes/skills/* "${STAGING_DIR}/skills/" 2>/dev/null || true
cp -r /data/.hermes/sessions/* "${STAGING_DIR}/interactions/" 2>/dev/null || true
cp -r /data/.hermes/enterprise/* "${STAGING_DIR}/enterprise/" 2>/dev/null || true

rm -f "${STAGING_DIR}/enterprise/config/env.conf"

cat << 'EOF_README' > "${STAGING_DIR}/README.md"
# 🚀 Hermes Enterprise: Advanced Backup & Evolution System

## 📋 Philosophy
- **Immutability**: Every interaction and memory is preserved.
- **Intelligence**: Self-analyzing and evolving core.
- **Security**: Built-in protection for sensitive credentials.

## 🏗 Repository Structure
- `core/`: System configuration and identity.
- `intelligence/`: Memories, context, and the SOUL.
- `skills/`: Custom and system-level capabilities.
- `interactions/`: Comprehensive session history and logs.
- `enterprise/`: Automation scripts and enterprise configuration.

## ⚙️ Automation
- **Sync Interval**: Every 12 hours.
- **Mode**: GitHub-Direct (No local persistence).
- **Tooling**: Integrated with Cron and Git-Sync.

---
*Generated by Hermes Enterprise System*
EOF_README

cat << 'EOF_GITIGNORE' > "${STAGING_DIR}/.gitignore"
*.lock
*.db*
*.sock
*.pid
auth.json
logs/
env.conf
.env
EOF_GITIGNORE

cd "${STAGING_DIR}"
git init -b main
git config user.name "Hermes Agent"
git config user.email "hermes@agent.local"
git add .
git commit -m "🚀 Enterprise Sync: Structured Backup ${TIMESTAMP}"

REPO_WITH_TOKEN="https://oauth2:${GIT_TOKEN}@github.com/${REPO_OWNER}/${REPO_NAME}.git"
git remote add origin "${REPO_WITH_TOKEN}"
git push -f origin main

echo "✅ Full structured sync completed: ${REPO_URL}"
rm -rf "${STAGING_DIR}"
